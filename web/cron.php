# This thing does everything
use App\Controller;

if (file_exists('../vendor/autoload.php')) {
    require '../vendor/autoload.php';
}

error_reporting(E_ALL);
ini_set('display_errors', '1');

$controller = new Controller(true);

if (gettype($controller->modules) == 'array') {
    foreach ($controller->modules as $name => $module) {
        if (method_exists($module, 'yore_cron')) {
            echo "Executing function yore_cron() in module: $name\n";
            $r = $module->yore_cron($controller);
            echo "$r\n";
        } else {
            echo "There is no function yore_cron() in module: $name\n";
        }
    }
}


// Autoload function
spl_autoload_register(function ($class_name) {
    // Define the base directory for the "App" namespace
    $base_dir = __DIR__ . '/../app/';

    // Check if the class is within the "App" namespace
    $namespace = 'App\\';
    if (strncmp($namespace, $class_name, strlen($namespace)) === 0) {
        // Remove the namespace prefix
        $relative_class = substr($class_name, strlen($namespace));

        // Replace the namespace separator with the directory separator
        $file = $base_dir . str_replace('\\', DIRECTORY_SEPARATOR, $relative_class) . '.php';

        // If the file exists, require it
        if (file_exists($file)) {
            require $file;
        }
    }
});
